function findNotes(text) {
  const low = text.toLowerCase();
  const found = [];
  const usedSpans = [];
  const keys = Object.keys(NOTE).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    const idx = low.indexOf(key);
    if (idx === -1) continue;
    const overlaps = usedSpans.some(([s, e]) => idx < e && idx + key.length > s);
    if (overlaps) continue;
    usedSpans.push([idx, idx + key.length]);
    found.push(key);
  }
  return found;
}

function joinList(items, lang) {
  if (items.length === 0) return null;
  if (items.length === 1) return items[0];
  if (lang === "en") return items.slice(0, -1).join(", ") + " and " + items[items.length - 1];
  if (lang === "uk") return items.slice(0, -1).join(", ") + " та " + items[items.length - 1];
  return items.slice(0, -1).join(", ") + " и " + items[items.length - 1];
}

const LANG_IDX = { en: 0, uk: 1, ru: 2 };

export function describeFlavour(rawFlavour) {
  const low = rawFlavour.toLowerCase();
  const isIce = /\bice\b|\blce\b/.test(low);
  const isSour = /\bsour\b/.test(low);
  const isNicFree = /nicotine free/.test(low);
  let seriesKey = null;
  for (const key of Object.keys(SERIES_NOTE)) {
    if (low.includes(key)) {
      seriesKey = key;
      break;
    }
  }

  const notes = findNotes(rawFlavour);
  const out = { en: null, uk: null, ru: null };
  const hasContent = notes.length > 0 || isSour;

  for (const lang of ["en", "uk", "ru"]) {
    const i = LANG_IDX[lang];
    if (!hasContent) {
      out[lang] = null;
      continue;
    }
    const nounPhrase = notes.length
      ? joinList(
          notes.map((n) => NOTE[n][i]),
          lang
        )
      : null;

    let sentence;
    if (nounPhrase) {
      sentence = lang === "en" ? `A blend of ${nounPhrase}` : lang === "uk" ? `Поєднання ${nounPhrase}` : `Сочетание ${nounPhrase}`;
    } else {
      // sour-only, no recognizable fruit note (e.g. "Sour G", "Sour Drop")
      sentence = lang === "en" ? "A tangy sour-candy flavour" : lang === "uk" ? "Кислуватий смак льодяника" : "Кисловатый вкус леденца";
    }

    if (isIce) sentence += ` ${MOD_ICE[i]}`;
    else if (isSour && nounPhrase) sentence += ` ${MOD_SOUR[i]}`;

    if (seriesKey) {
      sentence += ` — ${SERIES_NOTE[seriesKey][i]}.`;
    } else {
      sentence += ".";
    }

    if (isNicFree) sentence += MOD_NICFREE[i];

    out[lang] = sentence;
  }

  return out.en ? out : null;
}

const OHM_RE = /^\d+(\.\d+)?\s*OHM/i;
const COLOUR_WORDS = new Set([
  "black", "white", "silver", "gold", "blue", "green", "red", "pink", "purple", "grey", "gray", "brown",
  "orange", "yellow", "violet", "indigo", "navy", "teal", "bronze", "copper", "titanium", "chrome", "gunmetal",
]);

const SPECIAL_COLOUR = new Set(["meteor shower"]);

export function describeVariant(rawFlavour) {
  const low = rawFlavour.toLowerCase();
  if (OHM_RE.test(rawFlavour.trim())) {
    return {
      en: `Replacement coil, ${rawFlavour.trim()} resistance — lower ohm for bigger clouds and warmer vapour, higher ohm for a tighter, flavour-focused draw.`,
      uk: `Змінний випарник, опір ${rawFlavour.trim()} — менший опір дає більше пари, більший — щільнішу тягу з акцентом на смак.`,
      ru: `Сменный испаритель, сопротивление ${rawFlavour.trim()} — меньшее сопротивление даёт больше пара, большее — более плотную тягу с акцентом на вкус.`,
    };
  }
  const isAllCapsColour = rawFlavour === rawFlavour.toUpperCase() && rawFlavour.length > 2;
  const words = low.split(/\s+/);
  if (isAllCapsColour || words.some((w) => COLOUR_WORDS.has(w)) || SPECIAL_COLOUR.has(low)) {
    const pretty = rawFlavour
      .toLowerCase()
      .split(" ")
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(" ");
    return {
      en: `${pretty} colourway.`,
      uk: `Колірне виконання: ${pretty}.`,
      ru: `Цветовое исполнение: ${pretty}.`,
    };
  }
  return null;
}

export function describeAny(rawFlavour) {
  return describeFlavour(rawFlavour) ?? describeVariant(rawFlavour) ?? null;
}
